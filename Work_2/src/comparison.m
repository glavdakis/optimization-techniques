% Comparison of the number of iterations of steepest descent and Levenberg-Marquardt.
% Run steepest_descent.m and levenberg_marquardt.m first.

figure

x = categorical({'(0, 0)','(-1, 1)','(1, -1)'});
x = reordercats(x, {'(0, 0)','(-1, 1)','(1, -1)'});
% number of iterations = number of points - 1 (the starting point is not an iteration)
y = [ ...
    sd_const_step_zero_iter(1) sd_const_step_one_iter(1) sd_const_step_two_iter(1) ;...
    lm_const_step_zero_iter(1) lm_const_step_one_iter(1) lm_const_step_two_iter(1) ;...
    sd_min_step_zero_iter(1) sd_min_step_one_iter(1) sd_min_step_two_iter(1) ;...
    lm_min_step_zero_iter(1) lm_min_step_one_iter(1) lm_min_step_two_iter(1) ;...
    sd_armijo_step_zero_iter(1) sd_armijo_step_one_iter(1) sd_armijo_step_two_iter(1);...
    lm_armijo_step_zero_iter(1) lm_armijo_step_one_iter(1) lm_armijo_step_two_iter(1);...
    ]' - 1;
b = bar(x, y);

% logarithmic axis, so that small and large counts are both visible, with the value on each bar
set(gca, 'YScale', 'log');
ylim([0.5 3000]);
for k = 1:numel(b)
    text(b(k).XEndPoints, max(b(k).YEndPoints, 0.6), string(b(k).YData), ...
        'HorizontalAlignment', 'center', 'VerticalAlignment', 'bottom', 'FontSize', 8);
end

legend("Steepest descent, constant step = 0.1", "Levenberg-Marquardt, constant step = 0.1", ...
    "Steepest descent, minimizing step", "Levenberg-Marquardt, minimizing step", ...
    "Steepest descent, armijo rule step", "Levenberg-Marquardt, armijo rule step", 'Location', 'northwest');
xlabel("starting point");
ylabel("number of iterations (log scale)");
